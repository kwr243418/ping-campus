// 모델에 보내기 전 개인정보 마스킹: 전화번호·이메일·학번·카톡 대화 발신자 이름
export const MASK = "[마스킹]";

export function maskPersonalInfo(text: string): string {
  return (
    text
      // 이메일
      .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, MASK)
      // 전화번호 (휴대폰·지역번호)
      .replace(/(?<!\d)(?:01[016789]|0\d{1,2})[-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)/g, MASK)
      // 학번 (숫자 8~10자리)
      .replace(/(?<![\d.\-/:])\d{8,10}(?![\d.\-/:])/g, MASK)
      // 카톡 대화 발신자: "[홍길동] [오후 3:12] 메시지"
      .replace(/^\[[^\]\n]{1,20}\](?=\s*\[?(?:오전|오후)\s*\d{1,2}:\d{2})/gm, MASK)
      // 카톡 내보내기: "2026년 11월 18일 오후 3:12, 홍길동 : 메시지"
      .replace(/((?:오전|오후)\s*\d{1,2}:\d{2},\s*)[^:\n]{1,20}?\s*:\s/g, `$1${MASK} : `)
  );
}
